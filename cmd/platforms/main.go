// Command platforms keeps spec/platforms.json, the platforms HashiCorp
// publishes Packer plugins for, and renders it into the Go and console code
// that read it.
//
//	platforms fetch   # read releases.hashicorp.com, write spec/platforms.json
//	platforms render  # write internal/domain/plugin/platforms_gen.go and
//	                  # web/src/data/platforms.json from the snapshot
//
// fetch is the only step that touches the network; it runs from
// make platforms when a release is cut. render runs from make generate and
// is covered by make generate-check.
package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"net/http"
	"os"
	"sort"
	"strconv"
	"strings"
	"time"
)

const (
	indexURL     = "https://releases.hashicorp.com/index.json"
	snapshotPath = "spec/platforms.json"
	goPath       = "internal/domain/plugin/platforms_gen.go"
	webPath      = "web/src/data/platforms.json"
)

// Snapshot is spec/platforms.json: the union of the platforms each
// packer-plugin product's newest stable release was built for, with the
// per-product evidence beside it.
type Snapshot struct {
	Source      string    `json:"source"`
	GeneratedAt string    `json:"generated_at"`
	Products    []Product `json:"products"`
	Platforms   []string  `json:"platforms"`
}

type Product struct {
	Product   string   `json:"product"`
	Version   string   `json:"version"`
	Platforms []string `json:"platforms"`
}

func main() {
	if len(os.Args) != 2 {
		fmt.Fprintln(os.Stderr, "usage: platforms fetch|render")
		os.Exit(2)
	}
	var err error
	switch os.Args[1] {
	case "fetch":
		err = fetch()
	case "render":
		err = render()
	default:
		err = fmt.Errorf("unknown command %q", os.Args[1])
	}
	if err != nil {
		fmt.Fprintln(os.Stderr, "platforms:", err)
		os.Exit(1)
	}
}

func fetch() error {
	client := &http.Client{Timeout: 30 * time.Second}
	var index map[string]json.RawMessage
	if err := getJSON(client, indexURL, &index); err != nil {
		return err
	}
	var names []string
	for name := range index {
		if strings.HasPrefix(name, "packer-plugin-") {
			names = append(names, name)
		}
	}
	sort.Strings(names)
	var products []Product
	for _, name := range names {
		var listing struct {
			Versions map[string]struct {
				Builds []struct {
					OS   string `json:"os"`
					Arch string `json:"arch"`
				} `json:"builds"`
			} `json:"versions"`
		}
		if err := getJSON(client, "https://releases.hashicorp.com/"+name+"/index.json", &listing); err != nil {
			return err
		}
		latest := newestStable(keys(listing.Versions))
		if latest == "" {
			continue
		}
		var platforms []string
		for _, build := range listing.Versions[latest].Builds {
			platforms = append(platforms, build.OS+"_"+build.Arch)
		}
		products = append(products, Product{Product: name, Version: latest, Platforms: unique(platforms)})
	}
	snapshot := Snapshot{
		Source: indexURL, GeneratedAt: time.Now().UTC().Format(time.RFC3339),
		Products: products, Platforms: Union(products),
	}
	encoded, err := json.MarshalIndent(snapshot, "", "  ")
	if err != nil {
		return err
	}
	return os.WriteFile(snapshotPath, append(encoded, '\n'), 0o644)
}

// Union is every platform any product's newest stable release was built for.
func Union(products []Product) []string {
	var all []string
	for _, product := range products {
		all = append(all, product.Platforms...)
	}
	return unique(all)
}

func render() error {
	raw, err := os.ReadFile(snapshotPath)
	if err != nil {
		return err
	}
	var snapshot Snapshot
	if err := json.Unmarshal(raw, &snapshot); err != nil {
		return fmt.Errorf("decode %s: %w", snapshotPath, err)
	}
	if len(snapshot.Platforms) == 0 {
		return fmt.Errorf("%s lists no platforms", snapshotPath)
	}
	var goSource bytes.Buffer
	fmt.Fprintf(&goSource, "// Code generated by cmd/platforms from %s; DO NOT EDIT.\n\npackage plugin\n\n", snapshotPath)
	fmt.Fprintf(&goSource, "// PlatformsSnapshotDate is when %s was last fetched.\nconst PlatformsSnapshotDate = %q\n\n", snapshotPath, snapshot.GeneratedAt)
	fmt.Fprintf(&goSource, "// Platforms are the OS_ARCH pairs HashiCorp built its newest stable Packer\n// plugin releases for, as %s records them.\nvar Platforms = []string{\n", snapshotPath)
	for _, platform := range snapshot.Platforms {
		fmt.Fprintf(&goSource, "\t%q,\n", platform)
	}
	goSource.WriteString("}\n")
	formatted, err := format.Source(goSource.Bytes())
	if err != nil {
		return err
	}
	if err := os.WriteFile(goPath, formatted, 0o644); err != nil {
		return err
	}
	web, err := json.MarshalIndent(struct {
		GeneratedAt string   `json:"generated_at"`
		Platforms   []string `json:"platforms"`
	}{snapshot.GeneratedAt, snapshot.Platforms}, "", "  ")
	if err != nil {
		return err
	}
	return os.WriteFile(webPath, append(web, '\n'), 0o644)
}

func getJSON(client *http.Client, url string, into any) error {
	response, err := client.Get(url)
	if err != nil {
		return err
	}
	defer func() { _ = response.Body.Close() }()
	if response.StatusCode != http.StatusOK {
		return fmt.Errorf("GET %s: %s", url, response.Status)
	}
	// The product index carries every version of every product and runs to
	// tens of megabytes; decode it as it streams.
	if err := json.NewDecoder(response.Body).Decode(into); err != nil {
		return fmt.Errorf("decode %s: %w", url, err)
	}
	return nil
}

// newestStable is the highest version with no prerelease suffix, by numeric
// segment; the empty string when there is none.
func newestStable(versions []string) string {
	newest := ""
	for _, version := range versions {
		if strings.Contains(version, "-") {
			continue
		}
		if newest == "" || compareVersions(version, newest) > 0 {
			newest = version
		}
	}
	return newest
}

func compareVersions(a, b string) int {
	as, bs := strings.Split(a, "."), strings.Split(b, ".")
	for i := 0; i < len(as) || i < len(bs); i++ {
		var x, y int
		if i < len(as) {
			x, _ = strconv.Atoi(as[i])
		}
		if i < len(bs) {
			y, _ = strconv.Atoi(bs[i])
		}
		if x != y {
			return x - y
		}
	}
	return 0
}

func keys[V any](m map[string]V) []string {
	out := make([]string, 0, len(m))
	for k := range m {
		out = append(out, k)
	}
	return out
}

func unique(values []string) []string {
	seen := map[string]bool{}
	var out []string
	for _, value := range values {
		if !seen[value] {
			seen[value] = true
			out = append(out, value)
		}
	}
	sort.Strings(out)
	return out
}
